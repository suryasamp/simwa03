package com.simwa3.dto;

public class DTOWarga {

	private Integer id;
	private String nama_warga;
	private String nomer_hp;
	private String blok;
	private String nomer_rumah;
	private String code_warga;
	private String password_warga;
	private String role_warga;
	private String jabatan;

	public Integer getId() {
		return id;
	}

	public void setId(Integer id) {
		this.id = id;
	}

	public String getNama_warga() {
		return nama_warga;
	}

	public void setNama_warga(String nama_warga) {
		this.nama_warga = nama_warga;
	}

	public String getNomer_hp() {
		return nomer_hp;
	}

	public void setNomer_hp(String nomer_hp) {
		this.nomer_hp = nomer_hp;
	}

	public String getBlok() {
		return blok;
	}

	public void setBlok(String blok) {
		this.blok = blok;
	}

	public String getNomer_rumah() {
		return nomer_rumah;
	}

	public void setNomer_rumah(String nomer_rumah) {
		this.nomer_rumah = nomer_rumah;
	}

	public String getCode_warga() {
		return code_warga;
	}

	public void setCode_warga(String code_warga) {
		this.code_warga = code_warga;
	}

	public String getPassword_warga() {
		return password_warga;
	}

	public void setPassword_warga(String password_warga) {
		this.password_warga = password_warga;
	}

	public String getRole_warga() {
		return role_warga;
	}

	public void setRole_warga(String role_warga) {
		this.role_warga = role_warga;
	}

	public String getJabatan() {
		return jabatan;
	}

	public void setJabatan(String jabatan) {
		this.jabatan = jabatan;
	}

}
